//! Golden-set oracle scenarios (TASK-0313).
//!
//! Each test materializes a deterministic tree (`support::images` +
//! `support::tree`), runs the real `imgdedup --json` binary, and diffs the
//! **whole document** against a hand-derived expected manifest
//! (`support::oracle`). Keepers and orderings are made unambiguous *by
//! construction* (depth, name length, mtime) and the expectations below cite
//! the rule that decides them — the harness never re-computes pipeline logic.
//!
//! Orderings encoded in the manifests (ADR-0010 canonical order):
//! - groups appear by keeper path ascending;
//! - files within a group follow the active `--keep` total order;
//! - warnings are grouped by stage and sorted by path within each stage.

mod support;

use serde_json::{Value, json};
use support::images::{ALL_FORMATS, ImageFormat, image_bytes};
use support::oracle::{assert_json_eq, run_json, run_json_raw};
use support::tree::{FileSpec, LinkSpec, materialize};

/// Base mtime for files whose timestamp is not scenario-relevant.
const T: i64 = 1_600_000_000;

/// Shorthand for a JSON File object.
fn file(path: &str, size: u64, mtime: i64) -> Value {
    json!({ "path": path, "size": size, "mtime": mtime })
}

/// Shorthand for the common group shape without hard-link involvement.
fn plain_group(keeper: Value, removable: Vec<Value>, reclaimable_bytes: u64) -> Value {
    json!({
        "keeper": keeper,
        "removable": removable,
        "protected": [],
        "hard_link_sets": [],
        "reclaimable_bytes": reclaimable_bytes,
    })
}

/// Shorthand for the full document shell shared by all scenarios.
fn manifest(groups: Vec<Value>, already_deduplicated: Vec<Value>, totals: Value) -> Value {
    json!({
        "schema_version": 1,
        "mode": "dry-run",
        "groups": groups,
        "already_deduplicated": already_deduplicated,
        "totals": totals,
        "warnings": [],
        "root_errors": [],
    })
}

fn totals(
    duplicate_groups: u64,
    removable_files: u64,
    reclaimable_bytes: u64,
    already_deduplicated_sets: u64,
) -> Value {
    json!({
        "duplicate_groups": duplicate_groups,
        "removable_files": removable_files,
        "reclaimable_bytes": reclaimable_bytes,
        "already_deduplicated_sets": already_deduplicated_sets,
    })
}

fn spec(rel_path: &str, bytes: Vec<u8>, mtime: i64) -> FileSpec {
    FileSpec {
        rel_path: rel_path.to_owned(),
        bytes,
        mtime,
    }
}

/// Per-format duplicate-pair table, listed in keeper-path ascending order so
/// the expected `groups` array can be derived directly from it. Each format
/// gets a distinct seed, so no cross-format content collisions are possible.
const FORMAT_DIRS: [(&str, ImageFormat, u8); 8] = [
    ("bmp", ImageFormat::Bmp, 10),
    ("gif87a", ImageFormat::Gif87a, 20),
    ("gif89a", ImageFormat::Gif89a, 30),
    ("jpeg", ImageFormat::Jpeg, 40),
    ("png", ImageFormat::Png, 50),
    ("tiffbe", ImageFormat::TiffBe, 60),
    ("tiffle", ImageFormat::TiffLe, 70),
    ("webp", ImageFormat::Webp, 80),
];

/// Build the all-formats tree: one exact duplicate pair per supported
/// signature, `<dir>/a.<ext>` + `<dir>/copy.<ext>`, 64 bytes each.
fn materialize_all_formats(root: &std::path::Path) {
    let mut files = Vec::new();
    for (dir, format, seed) in FORMAT_DIRS {
        let ext = format.extension();
        let bytes = image_bytes(format, seed, 64);
        files.push(spec(&format!("{dir}/a.{ext}"), bytes.clone(), T));
        files.push(spec(&format!("{dir}/copy.{ext}"), bytes, T));
    }
    materialize(root, &files, &[]);
}

// ── Per-format pipeline coverage ─────────────────────────────────────────────

/// AC: every supported magic-byte signature flows enumerate → sniff → engine
/// and forms exactly one group per pair, with zero warnings (proving the
/// generated bytes are accepted as genuine images end-to-end).
///
/// Keeper derivation: equal depth (2 segments), so the char count decides —
/// `a.<ext>` is shorter than `copy.<ext>` (`--keep shortest` default).
#[test]
fn every_supported_format_flows_the_full_pipeline() {
    let dir = tempfile::tempdir().expect("tempdir");
    materialize_all_formats(dir.path());

    let groups: Vec<Value> = FORMAT_DIRS
        .iter()
        .map(|(d, format, _)| {
            let ext = format.extension();
            plain_group(
                file(&format!("{d}/a.{ext}"), 64, T),
                vec![file(&format!("{d}/copy.{ext}"), 64, T)],
                64,
            )
        })
        .collect();
    let expected = manifest(groups, vec![], totals(8, 8, 8 * 64, 0));

    let actual = run_json(dir.path(), &[]);
    assert_json_eq(&actual, &expected);
}

// ── Near-misses ──────────────────────────────────────────────────────────────

/// AC: files that *look* like duplicate candidates but are not byte-identical
/// never group — same format+size with different content (hash pre-filter),
/// same format with different size (size pre-grouping), and a different
/// format at the same size (content differs from byte 0).
#[test]
fn near_misses_never_form_groups() {
    let dir = tempfile::tempdir().expect("tempdir");
    materialize(
        dir.path(),
        &[
            spec("a.png", image_bytes(ImageFormat::Png, 1, 64), T),
            spec("b.png", image_bytes(ImageFormat::Png, 2, 64), T),
            spec("c.png", image_bytes(ImageFormat::Png, 1, 96), T),
            spec("d.bmp", image_bytes(ImageFormat::Bmp, 3, 64), T),
        ],
        &[],
    );

    let expected = manifest(vec![], vec![], totals(0, 0, 0, 0));

    let actual = run_json(dir.path(), &[]);
    assert_json_eq(&actual, &expected);
}

// ── Mislabeled and empty files ───────────────────────────────────────────────

/// AC (FR-3/NFR-2): non-image content named like an image is rejected at the
/// sniff stage with a warning and never grouped — even at the exact size of a
/// genuine duplicate pair in the same tree — and an empty file warns rather
/// than groups. Warnings appear sorted by path within the `sniff` stage.
#[test]
fn mislabeled_and_empty_files_warn_and_never_group() {
    let dir = tempfile::tempdir().expect("tempdir");
    let fake: Vec<u8> = b"definitely not an image "
        .iter()
        .copied()
        .cycle()
        .take(80)
        .collect();
    materialize(
        dir.path(),
        &[
            spec("real1.jpg", image_bytes(ImageFormat::Jpeg, 5, 80), T),
            spec("real2.jpg", image_bytes(ImageFormat::Jpeg, 5, 80), T),
            spec("fake.jpg", fake, T),
            spec("empty.jpg", Vec::new(), T),
        ],
        &[],
    );

    let expected = json!({
        "schema_version": 1,
        "mode": "dry-run",
        "groups": [plain_group(
            file("real1.jpg", 80, T),
            vec![file("real2.jpg", 80, T)],
            80,
        )],
        "already_deduplicated": [],
        "totals": totals(1, 1, 80, 0),
        "warnings": [
            { "stage": "sniff", "path": "empty.jpg", "reason": "file is empty" },
            {
                "stage": "sniff",
                "path": "fake.jpg",
                "reason": "content not recognized as a supported image format",
            },
        ],
        "root_errors": [],
    });

    let actual = run_json(dir.path(), &[]);
    assert_json_eq(&actual, &expected);
}

// ── Keeper rules ─────────────────────────────────────────────────────────────

/// AC (FR-9/FR-10): one tree, three runs, three different keepers — each
/// unambiguous by construction under its rule (ADR-0008 total orders):
///
/// | file                   | segments | mtime |
/// |------------------------|----------|-------|
/// | `k/keep.png`           | 2        | T+300 |
/// | `deep/nest/b.png`      | 3        | T+100 |
/// | `c-very-long-name.png` | 1        | T+200 |
///
/// - default (`shortest`): fewest segments → `c-very-long-name.png`;
///   removable ordered by segments: `k/keep.png`, then `deep/nest/b.png`.
/// - `--keep oldest`: oldest mtime → `deep/nest/b.png`; removable by mtime
///   ascending: `c-very-long-name.png` (T+200), then `k/keep.png` (T+300).
/// - `--keep newest`: newest mtime → `k/keep.png`; removable by mtime
///   descending: `c-very-long-name.png` (T+200), then `deep/nest/b.png`.
#[test]
fn keeper_rules_select_by_construction_unambiguous_keepers() {
    let dir = tempfile::tempdir().expect("tempdir");
    let bytes = image_bytes(ImageFormat::Png, 9, 64);
    materialize(
        dir.path(),
        &[
            spec("k/keep.png", bytes.clone(), T + 300),
            spec("deep/nest/b.png", bytes.clone(), T + 100),
            spec("c-very-long-name.png", bytes, T + 200),
        ],
        &[],
    );

    let cases: [(&[&str], Value, [Value; 2]); 3] = [
        (
            &[],
            file("c-very-long-name.png", 64, T + 200),
            [
                file("k/keep.png", 64, T + 300),
                file("deep/nest/b.png", 64, T + 100),
            ],
        ),
        (
            &["--keep", "oldest"],
            file("deep/nest/b.png", 64, T + 100),
            [
                file("c-very-long-name.png", 64, T + 200),
                file("k/keep.png", 64, T + 300),
            ],
        ),
        (
            &["--keep", "newest"],
            file("k/keep.png", 64, T + 300),
            [
                file("c-very-long-name.png", 64, T + 200),
                file("deep/nest/b.png", 64, T + 100),
            ],
        ),
    ];

    for (args, keeper, removable) in cases {
        let expected = manifest(
            vec![plain_group(keeper, removable.to_vec(), 128)],
            vec![],
            totals(1, 2, 128, 0),
        );
        let actual = run_json(dir.path(), args);
        assert_json_eq(&actual, &expected);
    }
}

// ── Hard links ───────────────────────────────────────────────────────────────

/// AC (FR-17/AC-18, ADR-0008 anchor rule): a hard-link anchor set with a
/// separate identical copy in scope is *protected* — listed, never removable,
/// contributing zero reclaimable bytes — and an all-anchor content group (two
/// hard-link sets sharing one content, no standalone copy) forms no group and
/// surfaces both sets as `already_deduplicated`. A normal pair in the same
/// tree still reclaims.
///
/// **Pinned current behavior (doc-vs-behavior gap, tracked as TASK-0316):**
/// a *lone* fully-hard-linked set (`j/j1.png` ≡ `j/j2.png`, no other file
/// with that content) appears **nowhere** in the output. The guide's
/// `already_deduplicated` description reads as if it should be listed, but
/// the engine discards the note when a hash group collapses to a single
/// representative (`process_hash_group`: fewer than two physical files).
/// This manifest asserts today's behavior; if the product-owner decides lone
/// sets should surface, this golden line is the one that flips.
#[test]
fn hard_link_sets_are_protected_or_already_deduplicated() {
    let dir = tempfile::tempdir().expect("tempdir");
    let anchored = image_bytes(ImageFormat::Png, 11, 64);
    let all_anchor = image_bytes(ImageFormat::Png, 12, 64);
    let normal = image_bytes(ImageFormat::Png, 13, 64);
    let lone_linked = image_bytes(ImageFormat::Png, 14, 64);
    materialize(
        dir.path(),
        &[
            spec("copy.png", anchored.clone(), T),
            spec("h/h1.png", anchored, T),
            spec("g/f1.png", all_anchor.clone(), T),
            spec("g/g1.png", all_anchor, T),
            spec("j/j1.png", lone_linked, T),
            spec("n1.png", normal.clone(), T),
            spec("n2.png", normal, T),
        ],
        &[
            LinkSpec {
                existing: "h/h1.png".to_owned(),
                new: "h/h2.png".to_owned(),
            },
            LinkSpec {
                existing: "g/f1.png".to_owned(),
                new: "g/f2.png".to_owned(),
            },
            LinkSpec {
                existing: "g/g1.png".to_owned(),
                new: "g/g2.png".to_owned(),
            },
            LinkSpec {
                existing: "j/j1.png".to_owned(),
                new: "j/j2.png".to_owned(),
            },
        ],
    );

    let expected = manifest(
        vec![
            // Keeper: `copy.png` (1 segment beats 2 under default shortest).
            // The anchor set {h1,h2} has an in-scope sibling copy, so every
            // path of it is protected and nothing in it is reclaimable.
            json!({
                "keeper": file("copy.png", 64, T),
                "removable": [],
                "protected": [file("h/h1.png", 64, T), file("h/h2.png", 64, T)],
                "hard_link_sets": [
                    { "representative": "h/h1.png", "siblings": ["h/h2.png"] },
                ],
                "reclaimable_bytes": 0,
            }),
            plain_group(file("n1.png", 64, T), vec![file("n2.png", 64, T)], 64),
        ],
        // The all-anchor {f1,f2} + {g1,g2} content group, sorted by
        // representative path. The lone {j1,j2} set is absent (see above).
        vec![
            json!({ "representative": "g/f1.png", "siblings": ["g/f2.png"] }),
            json!({ "representative": "g/g1.png", "siblings": ["g/g2.png"] }),
        ],
        totals(2, 1, 64, 2),
    );

    let actual = run_json(dir.path(), &[]);
    assert_json_eq(&actual, &expected);
}

// ── Determinism ──────────────────────────────────────────────────────────────

/// AC (NFR-3): two runs over the same tree emit byte-identical stdout.
#[test]
fn json_output_is_byte_identical_across_runs() {
    let dir = tempfile::tempdir().expect("tempdir");
    materialize_all_formats(dir.path());

    let first = run_json_raw(dir.path(), &[]);
    let second = run_json_raw(dir.path(), &[]);
    assert!(
        first.stdout == second.stdout,
        "--json stdout differed between two runs over identical state"
    );
    assert!(!first.stdout.is_empty(), "--json stdout must not be empty");
}

/// AC: the generator itself is deterministic and seed-distinct — equal
/// inputs give byte-identical output, differing seeds give differing bytes,
/// and the requested length is honored exactly, for every format.
#[test]
fn generator_is_deterministic_seed_distinct_and_length_exact() {
    for format in ALL_FORMATS {
        let a = image_bytes(format, 42, 64);
        let b = image_bytes(format, 42, 64);
        let c = image_bytes(format, 43, 64);
        assert_eq!(a, b, "{format:?}: equal inputs must give identical bytes");
        assert_ne!(
            a, c,
            "{format:?}: differing seeds must give differing bytes"
        );
        assert_eq!(a.len(), 64, "{format:?}: length must be honored exactly");
        assert_eq!(
            image_bytes(format, 42, support::images::MIN_LEN).len(),
            support::images::MIN_LEN,
            "{format:?}: MIN_LEN must be generable"
        );
    }
}
